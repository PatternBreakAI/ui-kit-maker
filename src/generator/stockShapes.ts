/* ── Stock organic silhouettes ─────────────────────────────────────────────
   Path-data silhouettes shipped with the app, drawn in-house as flat vectors
   to the published import spec (one closed filled outline, no strokes or
   transforms, outline touching all four edges of its box).

   They are NOT procedural: unlike the v19 library, geometry here is authored
   artwork, so each entry keeps its own source viewBox and the renderer maps
   it into a component the same way a user-imported silhouette is mapped —
   including the ~1.42× distortion cap, so a drawn proportion never smears
   when a wide component stretches it.

   Reached through the `stock:` Shape prefix. Adding an entry here plus its
   SilhouetteMeta row in silhouettes.ts is all a new stock shape needs. */

