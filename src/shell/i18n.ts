/* The app inherits the front door's language.

   The homepage persists an explicit language choice as `ui-generator-lang`
   (localStorage — the same place every preference in this product lives,
   synced to the cloud workspace when signed in). This module is the
   editor's side of that promise.

   Shape: a flat string table per locale, English as both the source of
   truth and the fallback — a missing key NEVER breaks the UI, it just
   speaks English for that string. Keys are added surface by surface;
   docs/editability-audit.md carries the phasing.

   t() resolves the locale PER CALL, not at module load — the editor
   chunk pre-warms on the landing page, and a language picked after that
   warm-up must still win (the module-load capture was a real bug:
   change language, open the editor, get English). A render is always
   downstream of a navigation or state change, so per-call reads stay
   correct with zero plumbing. */

export type Locale = "en" | "zh" | "fr" | "es" | "it" | "de" | "ja";

const LOCALES: Locale[] = ["en", "zh", "fr", "es", "it", "de", "ja"];

export function currentLocale(): Locale {
  try {
    const l = localStorage.getItem("ui-generator-lang");
    if (l && (LOCALES as string[]).includes(l)) return l as Locale;
  } catch { /* private mode */ }
  return "en";
}

